import { isAbsolute, relative, resolve } from 'node:path';
import { utcTime } from '../pc-backup/status.mjs';

const uuid = value => typeof value === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(value);
export const BACKUP_CHILD_ENV = ['PC_APP_BACKUP_STATUS_PATH', 'PC_APP_BACKUP_INSTANCE_ID', 'PC_APP_BACKUP_GENERATION', 'PC_APP_BACKUP_STARTED_AT', 'PC_APP_BACKUP_DATABASE_SYSTEM_IDENTIFIER'];

export function validateBackupOwnerConfig(config, env) {
  if (!isAbsolute(config.backupConfigFile ?? '') || !uuid(config.expectedBackupInstanceId) || !/^\d{10,20}$/.test(config.expectedBackupDatabaseSystemIdentifier ?? '')) throw Error('Pinned backup owner configuration required');
  if (BACKUP_CHILD_ENV.some(name => Object.hasOwn(env, name))) throw Error('Backup identity must be generated by the owning host');
}

export function backupChildEnvironment(config, supervisor, now = Date.now()) {
  const identity = supervisor?.identity;
  const path = supervisor?.statusPath;
  const offset = typeof path === 'string' ? relative(config.releaseDirectory, path) : '';
  if (!uuid(identity?.instanceId) || identity.instanceId !== config.expectedBackupInstanceId || !uuid(identity?.generation)
    || !Number.isFinite(utcTime(identity?.startedAt)) || utcTime(identity.startedAt) > now
    || !isAbsolute(path ?? '') || (!offset.startsWith('..') && !isAbsolute(offset)) || resolve(path) === resolve(config.releaseDirectory)
    || typeof supervisor?.stop !== 'function') throw Error('Owned backup identity does not match the pinned app');
  return {
    PC_APP_BACKUP_STATUS_PATH: path,
    PC_APP_BACKUP_INSTANCE_ID: identity.instanceId,
    PC_APP_BACKUP_GENERATION: identity.generation,
    PC_APP_BACKUP_STARTED_AT: identity.startedAt,
    PC_APP_BACKUP_DATABASE_SYSTEM_IDENTIFIER: config.expectedBackupDatabaseSystemIdentifier,
  };
}

export function backupRuntimeRecord(config, supervisor, now = Date.now()) {
  const bound = backupChildEnvironment(config, supervisor, now);
  return { identity: { ...supervisor.identity, databaseSystemIdentifier: bound.PC_APP_BACKUP_DATABASE_SYSTEM_IDENTIFIER }, statusPath: bound.PC_APP_BACKUP_STATUS_PATH };
}
