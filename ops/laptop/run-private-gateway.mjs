import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseEnv } from 'node:util';
import { createPrivateGateway } from './private-gateway.mjs';
const root = resolve(import.meta.dirname, '../..');
const local = parseEnv(readFileSync(resolve(root, '.contingency/local-app.env'), 'utf8'));
if (local.NEXT_PUBLIC_SUPABASE_URL !== 'http://127.0.0.1:8000') throw Error('Local API only');
const config = JSON.parse(readFileSync(resolve(root, '.contingency/private-trial.json'), 'utf8'));
if (!/^https:\/\/[a-z0-9-]+\.trycloudflare\.com$/.test(config.origin)) throw Error('Expected dedicated trial tunnel');
const server = createPrivateGateway({ ...config, anonKey: local.NEXT_PUBLIC_SUPABASE_ANON_KEY });
server.listen(3108, '127.0.0.1', () => console.log('Private trial gateway listening on loopback port 3108.'));
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => { server.closeAllConnections(); server.close(); });
