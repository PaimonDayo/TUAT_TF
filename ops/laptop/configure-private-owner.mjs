// Changes only the restored LOCAL account's password. Never the cloud account.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomBytes } from 'node:crypto';
import { parseEnv } from 'node:util';
import { createClient } from '@supabase/supabase-js';
const root = resolve(import.meta.dirname, '../..');
const file = resolve(root, '.contingency/private-trial.json');
if (existsSync(file)) throw Error('Owner already configured; stop gateway and review before rotating');
const email = (process.argv[2] ?? '').trim().toLowerCase();
const origin = (process.argv[3] ?? '').trim();
if (!email.includes('@') || !/^https:\/\/[a-z0-9-]+\.trycloudflare\.com$/.test(origin)) throw Error('Expected owner email and dedicated quick-tunnel URL');
const local = parseEnv(readFileSync(resolve(root, '.contingency/local-app.env'), 'utf8'));
if (local.NEXT_PUBLIC_SUPABASE_URL !== 'http://127.0.0.1:8000') throw Error('Local API only');
const sb = createClient(local.NEXT_PUBLIC_SUPABASE_URL, local.SUPABASE_SERVICE_ROLE_KEY, { auth: { autoRefreshToken: false, persistSession: false } });
const result = await sb.auth.admin.listUsers({ page: 1, perPage: 1000 });
if (result.error) throw Error('Cannot read local Auth');
const users = result.data.users.filter(u => u.email?.toLowerCase() === email);
if (users.length !== 1) throw Error('Expected exactly one matching restored local account');
const owner = users[0];
const password = randomBytes(24).toString('base64url');
const updated = await sb.auth.admin.updateUserById(owner.id, { password });
if (updated.error) throw Error('Cannot configure local trial password');
const config = { origin, email, userId: owner.id, password };
writeFileSync(file, JSON.stringify(config), { mode: 0o600, flag: 'wx' });
writeFileSync(resolve(root, '.contingency/PC試験版ログイン.txt'), `PC試験版（本人専用）\nURL: ${origin}\n専用パスワード: ${password}\n\n本番Googleパスワードは変更していません。\nこのファイルとパスワードは共有しないでください。\n入力はPC内だけに保存され、本番・スプシへ反映されません。\nPCのスリープ・終了・回線断で試験版は停止します。\n`, { mode: 0o600 });
console.log('Configured the matching local account. Private login details saved locally, never printed.');
